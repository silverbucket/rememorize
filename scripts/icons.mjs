/**
 * Regenerates the app icons in public/ and the logos in docs/assets/ from the
 * brain in public/icon.svg, so they all stay the same shape and colours.
 *
 *   bun run icons
 *
 * The PNGs are rendered with Playwright's Chromium (`PW_CHANNEL=chrome` uses
 * your own Chrome). The wordmark's letters are Newsreader 600, already
 * converted to outlines: an SVG shown as an image can't load the app's fonts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");
const ASSETS = join(ROOT, "docs/assets");

/** Keep in step with src/app.css: the dark page, and the accent in each theme. */
const BOARD = "#151d19";
const MINT = "#77de96";
const CHALK = "#e4eae2";
/** A green that reads on white and on a dark page alike, for images that can't tell which they are on. */
const EITHER = "#158f44";

const BRAIN = readFileSync(join(PUBLIC, "icon.svg"), "utf-8").match(/<path[^>]* d="([^"]+)"/)?.[1];
if (!BRAIN) throw new Error("public/icon.svg has no path to draw the icons from");
const WORDMARK = JSON.parse(readFileSync(join(ASSETS, "wordmark.json"), "utf-8"));

const brain = (fill, attrs = "") => `<path ${attrs} fill="${fill}" fill-rule="evenodd" d="${BRAIN}"/>`;

/** The brain on the dark tile. `scale` leaves room for a launcher's mask. */
const tile = (scale) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <rect width="100" height="100" fill="${BOARD}"/>
  ${brain(MINT, `transform="translate(${50 - 48.2 * scale} ${50 - 52.2 * scale}) scale(${scale})"`)}
</svg>`;

/** The brain and the name, side by side. */
const lockup = (
    mark,
    word,
) => `<svg viewBox="0 0 ${Math.ceil(WORDMARK.width + 2)} 44" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="Rememorize">
  <!-- Generated by scripts/icons.mjs. The brain is public/icon.svg; the letters are Newsreader, as outlines. -->
  ${brain(mark, 'transform="translate(-2 0) scale(0.44)"')}
  <path fill="${word}" d="${WORDMARK.d}"/>
</svg>
`;

writeFileSync(join(ASSETS, "rememorize.svg"), lockup(EITHER, EITHER));
writeFileSync(join(ASSETS, "rememorize-dark.svg"), lockup(MINT, CHALK));

const PNGS = [
    ["favicon-32.png", 32, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="6 10 84 84">${brain(EITHER)}</svg>`],
    ["apple-touch-icon.png", 180, tile(0.82)],
    ["icon-192.png", 192, tile(0.82)],
    ["icon-512.png", 512, tile(0.82)],
    ["icon-maskable-512.png", 512, tile(0.6)],
];

const browser = await chromium.launch({ channel: process.env.PW_CHANNEL || undefined });
try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    for (const [name, size, svg] of PNGS) {
        await page.setViewportSize({ width: size, height: size });
        await page.setContent(
            `<style>html, body { margin: 0; background: transparent; } svg { display: block; width: ${size}px; height: ${size}px; }</style>${svg}`,
        );
        await page.screenshot({ path: join(PUBLIC, name), omitBackground: true });
    }
    console.log(`Wrote ${PNGS.length} icons to ${PUBLIC} and 2 logos to ${ASSETS}`);
} finally {
    await browser.close();
}
